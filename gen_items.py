"""ROM item data -> items.h: who can equip each piece of equipment, and what it gives.
  gen_items.py <dir with the unpacked itemdt_<w,s,b,u,h,a,l,d> archives> <arm9.bin> items.h
Each itemdt_<x> member (any language: the data parts are the same) holds n 32-byte index records
(+0 stat index, +0x18 price << 16 | asset) and then n 32-byte stat records:
  h0  type << 7 | 1 (weapons: 1 sword .. 12 bow, 13 shield)
  h2  vocation mask (bit v-1 for game vocation v; torso adds 0x2000) - not for weapons and shields
  h4h5 attack, defence, ?    h6h7 block, evasion, critical (per mille)    h8h9 deftness, agility, magical might
  h10h11 magical mending, ?, max MP                                       (each 10 bits, signed)
Weapons and shields go by the vocation's skill lines (arm9 0x020EE748: 5 per vocation, 1..12 weapons,
13 shield, 14 fisticuffs), as the game's own lists do."""
import struct, sys, glob, os

CATS = 'wsbuhald'          # weapon, shield, torso, legs, head, arms, feet, accessory (the bag order)
def s10(v): v &= 0x3FF; return v - 1024 if v & 0x200 else v

def main(src, arm9, out):
    a9 = open(arm9, 'rb').read(); o = 0x020EE748 - 0x02000000
    lines = [list(a9[o + 5 * v:o + 5 * v + 5]) for v in range(13)]
    rows = []
    for ci, c in enumerate(CATS):
        f = sorted(glob.glob(os.path.join(src, 'itemdt_' + c, '*.bin')))[0]
        X = open(f, 'rb').read(); n = struct.unpack_from('<H', X, 0)[0]
        for k in range(n):
            ir = struct.unpack_from('<8I', X, 0xC + 32 * k)
            h = struct.unpack_from('<16H', X, 0xC + 32 * n + 32 * ir[0])
            asset, price = ir[6] & 0xFFFF, ir[6] >> 16
            t = h[0] >> 7
            if c == 'w':
                assert 1 <= t <= 12, (hex(asset), t)
                mask = sum(1 << (v - 1) for v in range(1, 13) if t in lines[v][:4])
            elif c == 's':
                assert t == 13
                mask = sum(1 << (v - 1) for v in range(1, 13) if 13 in lines[v])
            else:
                mask = h[2] & 0xFFF
            u = lambda a, b: h[a] | h[b] << 16
            w45, w67, w89, w1011 = u(4, 5), u(6, 7), u(8, 9), u(10, 11)
            st = [s10(w45), s10(w45 >> 10), s10(w89 >> 10), s10(w89), s10(w89 >> 20), s10(w1011), s10(w1011 >> 20),
                  s10(w67), s10(w67 >> 10), s10(w67 >> 20)]
            rows.append((asset, ci, mask, min(price, 65535), st))
    rows.sort()
    assert len({r[0] for r in rows}) == len(rows)
    with open(out, 'w') as F:
        F.write('/* generated by gen_items.py from the ROM\'s itemdt data: do not edit */\n')
        F.write('#define IT_N %d\n' % len(rows))
        F.write('/* stats: attack, defence, agility, deftness, magical might, magical mending, max MP, block, evasion, critical (per mille) */\n#define IT_NS 10\n')
        F.write('static const u16 it_asset[IT_N] = {%s};\n' % ','.join(str(r[0]) for r in rows))
        F.write('static const u8 it_cat[IT_N] = {%s};\n' % ','.join(str(r[1]) for r in rows))
        F.write('static const u16 it_mask[IT_N] = {%s};\n' % ','.join(str(r[2]) for r in rows))
        F.write('static const u16 it_price[IT_N] = {%s};\n' % ','.join(str(r[3]) for r in rows))
        F.write('static const short it_stat[IT_N][IT_NS] = {%s};\n' % ','.join('{%s}' % ','.join(map(str, r[4])) for r in rows))
    print(len(rows), 'items')
    return rows

if __name__ == '__main__':
    rows = main(*sys.argv[1:4])
