"""skills.txt -> skills.h: the tables behind the spell and ability editor.
Bit b (0..359): b < 288 is an ability (record + 0x8B0 + b/8), else a spell (record + 0x8D4 + (b-288)/8)."""
import os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))

# (key in skills.txt, menu label, parent: 0 spells, 1 weapon skills, 2 other skills)
GROUPS = [
    ('attack', 'Attack spells', 0), ('healing', 'Healing and revival', 0), ('support', 'Buffs, debuffs and status', 0), ('field', 'Travel', 0),
    ('sword', 'Sword', 1), ('spear', 'Spear', 1), ('knife', 'Knife', 1), ('axe', 'Axe', 1), ('hammer', 'Hammer', 1), ('staff', 'Staff', 1),
    ('wand', 'Wand', 1), ('whip', 'Whip', 1), ('claw', 'Claw', 1), ('fan', 'Fan', 1), ('boomerang', 'Boomerang', 1), ('bow', 'Bow', 1),
    ('shield', 'Shield', 1), ('fisticuffs', 'Fisticuffs', 1),
    ('courage', 'Courage (warrior)', 2), ('faith', 'Faith (priest)', 2), ('spellcraft', 'Spellcraft (mage)', 2),
    ('focus', 'Focus (martial artist)', 2), ('acquisitiveness', 'Acquisitiveness (thief)', 2), ('litheness', 'Litheness (minstrel)', 2),
    ('guts', 'Guts (gladiator)', 2), ('fource', 'Fource (armamentalist)', 2), ('virtue', 'Virtue (paladin)', 2),
    ('enlightenment', 'Enlightenment (sage)', 2), ('je ne sais quoi', 'Je ne sais quoi (luminary)', 2),
    ('ruggedness', 'Ruggedness (ranger)', 2), ('hero', 'Other', 2),
]
KEY = {g[0]: i for i, g in enumerate(GROUPS)}
# index of each skill line's points in the record's skill point bytes (+0x428, eidako2's CHRSKILLPTS)
LINE = {k: i + 1 for i, k in enumerate(['sword', 'spear', 'knife', 'wand', 'whip', 'staff', 'claw', 'fan', 'axe', 'hammer',
        'boomerang', 'bow', 'shield', 'fisticuffs', 'courage', 'faith', 'spellcraft', 'focus', 'acquisitiveness',
        'litheness', 'guts', 'fource', 'virtue', 'enlightenment', 'je ne sais quoi', 'ruggedness'])}
SMALL = {'of', 'a', 'in', 'on', 'for', "'n'"}

def title(s):
    w = s.split(' ')
    out = []
    for i, x in enumerate(w):
        if x in ('hp', 'mp'): out.append(x.upper())
        elif i and x in SMALL: out.append(x)
        else: out.append(x[:1].upper() + x[1:])
    return ' '.join(out)

def parse():
    ents, sect, seen = [], None, set()
    for ln in open(os.path.join(HERE, 'skills.txt'), encoding='utf-8'):
        ln = ln.strip()
        if not ln or ln.startswith('#'): continue
        if ln.startswith('['): sect = ln.strip('[]'); continue
        m = re.match(r'^([0-9A-F]{2}):([0-9A-F]{2})\s+(.*?)(?:\s+(\d+))?\s+-\s+(.+)$', ln)
        assert m, ln
        byte, mask, grp, pts, name = int(m[1], 16), int(m[2], 16), m[3], m[4], m[5]
        assert mask and mask & (mask - 1) == 0, ln
        bit = byte * 8 + mask.bit_length() - 1
        if sect == 'spells': assert byte < 9; bit += 288
        else: assert sect == 'abilities' and byte < 36
        assert bit not in seen, ln; seen.add(bit)
        assert grp in KEY, grp
        assert (sect == 'spells') == (GROUPS[KEY[grp]][2] == 0), ln
        label = (pts + ': ' if pts else '') + title(name)
        ents.append((KEY[grp], int(pts) if pts else 1000, len(ents), bit, label, LINE.get(grp, 0) if pts else 0))
    ents.sort()
    return ents

def wlit(strs):
    s = ''.join(x.replace('\\', '\\\\').replace('"', '\\"') + '\\0' for x in strs)
    return 'u"' + s + '"'

def main(out):
    e = parse()
    known = [0] * 45
    for x in e: known[x[3] >> 3] |= 1 << (x[3] & 7)
    L = ['/* generated by gen_skills.py from skills.txt; do not edit */',
         '#define SK_N %d' % len(e), '#define SK_NGROUP %d' % len(GROUPS),
         'static const u16 sk_bit[SK_N] = {%s};' % ','.join(str(x[3]) for x in e),
         'static const u8 sk_group[SK_N] = {%s};' % ','.join(str(x[0]) for x in e),
         '/* the skill line (index into the skill point bytes, 0: none) and the points that earn it */',
         'static const u8 sk_line[SK_N] = {%s};' % ','.join(str(x[5]) for x in e),
         'static const u8 sk_pts[SK_N] = {%s};' % ','.join(str(x[1] if x[5] else 0) for x in e),
         'static const wchar sk_names[] = %s;' % wlit(x[4] for x in e),
         'static const u8 sk_group_parent[SK_NGROUP] = {%s};' % ','.join(str(g[2]) for g in GROUPS),
         'static const wchar sk_group_names[] = %s;' % wlit(g[1] for g in GROUPS),
         'static const u8 sk_known[45] = {%s};' % ','.join('0x%02x' % k for k in known), '']
    open(out, 'w', encoding='utf-8').write('\n'.join(L))
    print('%d spells and abilities (%d spells) in %d groups' % (len(e), sum(1 for x in e if x[3] >= 288), len(GROUPS)))

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'skills.h'))
